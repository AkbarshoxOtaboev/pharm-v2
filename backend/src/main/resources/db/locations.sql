CREATE TABLE IF NOT EXISTS regions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        character varying(255) NOT NULL,
    status      character varying(255),
    created_at  date,
    updated_at  date,
    CONSTRAINT regions_status_check CHECK (status IS NULL OR status IN ('ACTIVE', 'BLOCKED', 'DELETED'))
);

CREATE TABLE IF NOT EXISTS districts (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        character varying(255) NOT NULL,
    region_id   bigint NOT NULL REFERENCES regions(id),
    status      character varying(255),
    created_at  date,
    updated_at  date,
    CONSTRAINT districts_status_check CHECK (status IS NULL OR status IN ('ACTIVE', 'BLOCKED', 'DELETED'))
);

ALTER TABLE orders ADD COLUMN IF NOT EXISTS region_id bigint REFERENCES regions(id);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS district_id bigint REFERENCES districts(id);

ALTER TABLE orders DROP COLUMN IF EXISTS city_id;
